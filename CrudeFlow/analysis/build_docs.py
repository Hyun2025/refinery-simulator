from pathlib import Path
import json, html, re

root = Path(__file__).resolve().parent.parent
a = root / "analysis"


def render(txt):
    lines = txt.splitlines()
    out = []
    i = 0

    def inline(v):
        v = html.escape(v)
        return re.sub(r"`([^`]+)`", r"<code>\1</code>", v)

    while i < len(lines):
        l = lines[i].strip()
        if not l:
            i += 1
            continue
        if l.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append([c.strip() for c in lines[i].strip().strip("|").split("|")])
                i += 1
            out.append('<div class="scroll"><table>')
            for j, row in enumerate(rows):
                if all(re.fullmatch(r"[:\- ]+", c or "-") for c in row):
                    continue
                tag = "th" if j == 0 else "td"
                out.append("<tr>" + "".join(f"<{tag}>{inline(c)}</{tag}>" for c in row) + "</tr>")
            out.append("</table></div>")
            continue
        m = re.match(r"^(#{1,6}) (.*)", l)
        if m:
            out.append(f"<h{len(m[1])}>{inline(m[2])}</h{len(m[1])}>")
        elif l.startswith("- "):
            out.append("<p>• " + inline(l[2:]) + "</p>")
        else:
            out.append("<p>" + inline(l) + "</p>")
        i += 1
    return "".join(out)


catalog = []
for name, label, folder in [
    ("REPORT", "분석 결과", a),
    ("METHOD", "방법론", a),
    ("DATA", "데이터 설명", a),
    ("REQUIREMENTS", "요건 충족 근거", a),
    ("README", "실행 안내", root),
]:
    entry = {"title": label}
    for lang in ["ko", "en"]:
        p = folder / (name + "." + lang + ".md")
        entry[lang] = {"html": render(p.read_text()), "path": str(p.relative_to(root))}
    catalog.append(entry)
# Store generated HTML in readable pieces rather than one enormous source line.
source = json.dumps(catalog, ensure_ascii=False, indent=2)
for entry in catalog:
    for lang in ["ko", "en"]:
        original = entry[lang]["html"]
        pieces = original.replace("><", ">\n<").splitlines()
        readable = json.dumps(pieces, ensure_ascii=False, indent=2) + '.join("\\n")'
        source = source.replace(json.dumps(original, ensure_ascii=False), readable, 1)
(root / "docs-data.js").write_text(
    "// Generated by analysis/build_docs.py; edit the Markdown originals.\nwindow.CF_DOCS = "
    + source
    + ";\n"
)
